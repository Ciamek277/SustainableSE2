"""Run each benchmarks/ecoN/{bad,good}.py repeatedly; write CSV + summary.json."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path
from statistics import median

REPO_ROOT = Path(__file__).resolve().parent.parent
BENCHMARKS = REPO_ROOT / "benchmarks"
RESULTS = Path(__file__).resolve().parent / "results"

sys.path.insert(0, str(REPO_ROOT))

from experiments.codecarbon_utils import proxy_scale_factors, run_script_measured  # noqa: E402


def _median(xs: list[float]) -> float:
    return 0.0 if not xs else float(median(xs))


def _eco_dirs() -> list[Path]:
    return sorted(d for d in BENCHMARKS.iterdir() if d.is_dir() and d.name.startswith("eco"))


def run_all(*, repeats: int = 30) -> Path:
    RESULTS.mkdir(parents=True, exist_ok=True)
    raw_path = RESULTS / "raw_runs.csv"
    rows: list[dict] = []

    for eco in _eco_dirs():
        rule = eco.name.upper()
        bad = eco / "bad.py"
        good = eco / "good.py"
        if not bad.is_file() or not good.is_file():
            continue
        for variant, script in (("bad", bad), ("good", good)):
            for run in range(1, repeats + 1):
                m = run_script_measured(script)
                rows.append(
                    {
                        "rule": rule,
                        "variant": variant,
                        "run": run,
                        "energy_j": m["energy_j"],
                        "co2_kg": m["co2_kg"],
                        "duration_s": m["duration_s"],
                    }
                )

    fieldnames = ["rule", "variant", "run", "energy_j", "co2_kg", "duration_s"]
    with raw_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for row in rows:
            w.writerow(row)

    summary = _summarize(rows, repeats=repeats, proxy=proxy_scale_factors())
    summary_path = RESULTS / "summary.json"
    with summary_path.open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    return summary_path


def _summarize(
    rows: list[dict], repeats: int, *, proxy: tuple[float, float]
) -> dict:
    rules_out: dict = {}
    by_rule: dict[str, list[dict]] = {}
    for row in rows:
        by_rule.setdefault(row["rule"], []).append(row)

    max_delta_j = 1e-12
    deltas: dict[str, float] = {}

    for rule, rs in by_rule.items():
        bad_e = [float(r["energy_j"]) for r in rs if r["variant"] == "bad"]
        good_e = [float(r["energy_j"]) for r in rs if r["variant"] == "good"]
        bad_c = [float(r["co2_kg"]) for r in rs if r["variant"] == "bad"]
        good_c = [float(r["co2_kg"]) for r in rs if r["variant"] == "good"]
        bad_t = [float(r["duration_s"]) for r in rs if r["variant"] == "bad"]
        good_t = [float(r["duration_s"]) for r in rs if r["variant"] == "good"]
        med_bad = _median(bad_e)
        med_good = _median(good_e)
        delta_j = max(0.0, med_bad - med_good)
        med_bad_c = _median(bad_c)
        med_good_c = _median(good_c)
        delta_co2_kg = max(0.0, med_bad_c - med_good_c)
        med_bad_d = _median(bad_t)
        med_good_d = _median(good_t)
        delta_d = max(0.0, med_bad_d - med_good_d)
        deltas[rule] = delta_j
        max_delta_j = max(max_delta_j, delta_j)
        rules_out[rule] = {
            "delta_joules_median": delta_j,
            "delta_co2_grams_median": delta_co2_kg * 1000.0,
            "delta_duration_s_median": delta_d,
            "median_duration_bad_s": med_bad_d,
            "median_duration_good_s": med_good_d,
        }

    for rule, entry in rules_out.items():
        d = deltas.get(rule, 0.0)
        w = 0.25 + (d / max_delta_j) * 1.75 if max_delta_j > 0 else 1.0
        entry["weight"] = round(min(2.0, max(0.25, w)), 3)

    jps, cps = proxy
    return {
        "note": (
            "Generated by experiments/benchmark_runner.py (category estimates, not per-user truth). "
            "See delta_duration_s_median for wall-clock separation; proxy J/CO2 scale with "
            "GREENLINT_PROXY_J_PER_S / GREENLINT_PROXY_CO2_KG_PER_S."
        ),
        "repeats": repeats,
        "proxy_joules_per_second": jps,
        "proxy_co2_kg_per_second": cps,
        "rules": rules_out,
    }
